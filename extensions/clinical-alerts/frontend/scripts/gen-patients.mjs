// Bakes the synthetic member list into the frontend at build time (runs as npm "prebuild").
// Source of truth: data/synthetic-patients/index.json (Stephen's). If it isn't reachable (a build outside
// the repo), the committed src/app/patients.generated.ts is kept as-is.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const src = resolve(here, '../../../../data/synthetic-patients/index.json');
const out = resolve(here, '../src/app/patients.generated.ts');

if (!existsSync(src)) {
  console.warn(`gen-patients: ${src} not found; keeping the committed patients.generated.ts`);
  process.exit(0);
}

const index = JSON.parse(readFileSync(src, 'utf8'));
const patients = (index.patients ?? []).map(p => ({
  id: p.id, name: p.name, age: p.age, sex: p.sex, memberSince: p.memberSince,
}));

writeFileSync(out, `// GENERATED by scripts/gen-patients.mjs from data/synthetic-patients/index.json. Do not edit.
export interface SyntheticPatient { id: string; name: string; age: number; sex: string; memberSince: string; }

export const PATIENTS: SyntheticPatient[] = ${JSON.stringify(patients, null, 2)};
`);
console.log(`gen-patients: wrote ${patients.length} members`);
